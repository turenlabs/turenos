//! Cryptographic constant tables for findcrypt-style detection.
//!
//! Provenance:
//! - AES tables are generated at compile time from the FIPS-197 definition:
//!   the S-box is the GF(2^8) multiplicative inverse composed with the
//!   standard affine transform, T-tables are the classic xtime-expanded
//!   round tables (Te0-Te3, Td0-Td3) as used by OpenSSL-style code, and Rcon
//!   is the x^i chain in GF(2^8).
//! - SHA-1/SHA-2 initial vectors come from FIPS 180-4 section 5.
//! - The MD5 T-table is `floor(2^32 * abs(sin(i)))` per RFC 1321 section 3.4;
//!   unit tests recompute it from that formula.
//! - ChaCha20 / Salsa20 sigma and tau constants come from RFC 8439 and
//!   D. J. Bernstein's Salsa20 specification.
//! - Camellia SBOX1 and the six 64-bit Sigma key-schedule constants are
//!   transcribed from RFC 3713 sections 2.2 and 2.4.1.
//! - Serpent S-boxes are the eight 4-bit tables from the Serpent AES
//!   submission (Anderson/Biham/Knudsen, 1998).
//! - Twofish q0/q1 are the fixed 8-bit permutations from the Twofish paper
//!   (Schneier et al.), byte tables as published in reference code.
//! - Blowfish P-array and S-boxes are the hexadecimal digits of pi per
//!   Schneier's Blowfish specification (transcribed from reference sources).
//! - DES S-boxes are the eight 4x16 tables from FIPS 46-3.
//! - DER OIDs are the standard algorithm-identifier and named-curve
//!   encodings from RFC 3279/5480/8410/5758 et al.
//! - PKCS#1/PKCS#8/SPKI templates are DER header byte sequences from
//!   RFC 8017/5208/5280; CAPI blob magics are Microsoft BLOBHEADER values.
//! - bcrypt/argon2id prefixes are the modular-crypt identifiers from their
//!   specifications; PEM armor strings are RFC 7468 labels; "eyJ" constants
//!   are the fixed base64url prefixes of JSON JWT headers (RFC 7519).

// ---------------------------------------------------------------------------
// AES (FIPS-197) — generated at compile time from the specification math.

const fn xtime(x: u8) -> u8 {
    let carry = if x & 0x80 != 0 { 0x1b } else { 0 };
    (x << 1) ^ carry
}

const fn gf_mul(mut a: u8, mut b: u8) -> u8 {
    let mut r = 0u8;
    while b != 0 {
        if b & 1 != 0 {
            r ^= a;
        }
        a = xtime(a);
        b >>= 1;
    }
    r
}

const fn gf_pow(mut x: u8, mut e: u16) -> u8 {
    let mut r = 1u8;
    while e > 0 {
        if e & 1 == 1 {
            r = gf_mul(r, x);
        }
        x = gf_mul(x, x);
        e >>= 1;
    }
    r
}

const fn gf_inv(x: u8) -> u8 {
    if x == 0 {
        0
    } else {
        gf_pow(x, 254)
    }
}

const fn sbox_byte(x: u8) -> u8 {
    let i = gf_inv(x);
    i ^ i.rotate_left(1) ^ i.rotate_left(2) ^ i.rotate_left(3) ^ i.rotate_left(4) ^ 0x63
}

/// AES S-box (FIPS-197 Figure 7).
pub const AES_SBOX: [u8; 256] = {
    let mut t = [0u8; 256];
    let mut i = 0usize;
    while i < 256 {
        t[i] = sbox_byte(i as u8);
        i += 1;
    }
    t
};

/// AES inverse S-box (FIPS-197 Figure 14).
pub const AES_INV_SBOX: [u8; 256] = {
    let mut t = [0u8; 256];
    let mut i = 0usize;
    while i < 256 {
        t[AES_SBOX[i] as usize] = i as u8;
        i += 1;
    }
    t
};

/// AES round constants Rcon[1..=10] (FIPS-197 section 5.2).
pub const AES_RCON: [u8; 10] = {
    let mut t = [0u8; 10];
    let mut c = 0x01u8;
    let mut i = 0usize;
    while i < 10 {
        t[i] = c;
        c = xtime(c);
        i += 1;
    }
    t
};

const fn te0_word(i: usize) -> u32 {
    let s = AES_SBOX[i];
    let s2 = xtime(s);
    let s3 = s2 ^ s;
    ((s2 as u32) << 24) | ((s as u32) << 16) | ((s as u32) << 8) | (s3 as u32)
}

const fn td0_word(i: usize) -> u32 {
    let s = AES_INV_SBOX[i];
    ((gf_mul(s, 0x0e) as u32) << 24)
        | ((gf_mul(s, 0x09) as u32) << 16)
        | ((gf_mul(s, 0x0d) as u32) << 8)
        | (gf_mul(s, 0x0b) as u32)
}

const fn te_table(shift: u8) -> [u32; 256] {
    let mut t = [0u32; 256];
    let mut i = 0usize;
    while i < 256 {
        t[i] = te0_word(i).rotate_right(shift as u32);
        i += 1;
    }
    t
}

const fn td_table(shift: u8) -> [u32; 256] {
    let mut t = [0u32; 256];
    let mut i = 0usize;
    while i < 256 {
        t[i] = td0_word(i).rotate_right(shift as u32);
        i += 1;
    }
    t
}

